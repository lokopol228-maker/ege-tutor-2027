import type { ModeId, SubjectKey } from "@/lib/subjects";
import { SUBJECTS } from "@/lib/subjects";

type ChatTurn = { role: "user" | "assistant"; content: string };

/**
 * Полностью бесплатный репетитор без внешних API.
 * Ведёт по заранее заданным шагам и проверяет ключевые маркеры ответа.
 */
export function offlineTutorReply(params: {
  subject: SubjectKey;
  mode: ModeId;
  history: ChatTurn[];
}): string {
  const userTurns = params.history.filter((h) => h.role === "user");
  const step = userTurns.length;
  const last = (userTurns[userTurns.length - 1]?.content || "").toLowerCase();
  const meta = SUBJECTS[params.subject];

  if (params.mode === "review") {
    return reviewFlow(params.subject, last, step);
  }

  if (params.mode === "blitz") {
    return blitzFlow(params.subject, last, step);
  }

  return topicFlow(params.subject, meta.goal, last, step);
}

function topicFlow(subject: SubjectKey, goal: string, last: string, step: number): string {
  switch (subject) {
    case "MATH":
      return mathFlow(last, step, goal);
    case "RUSSIAN":
      return russianFlow(last, step, goal);
    case "INF":
      return infFlow(last, step, goal);
    case "ESSAY":
      return essayFlow(last, step, goal);
  }
}

function mathFlow(last: string, step: number, goal: string): string {
  if (step <= 1) {
    const hasBase = /x\s*>\s*1|основан|a\s*>\s*0|аргумент|одз/.test(last);
    const hasNotOne = /≠\s*1|не\s*равно\s*1|!=\s*1/.test(last);
    if (hasBase && (hasNotOne || /x-1/.test(last))) {
      return `ОДЗ начал верно держать — хорошо.\n\nБаза: для log_a(b) нужно a>0, a≠1, b>0.\n\nСледующий шаг: запиши ОДЗ для нашего неравенства **списком условий** (не решай само неравенство).\n\n[Текущий фокус: №15 логарифмы / ОДЗ] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 45/100 · цель ${goal}]`;
    }
    return `Пока ОДЗ неполное.\n\nМикрошаг: перечисли 3 условия для log_a(b). Не решай неравенство целиком.\n\nПодсказка: смотри на основание и на выражение под логарифмом.\n\n[Текущий фокус: ОДЗ логарифма] | [Статус: 🟥 Пробел] | [Ментальный балл: 30/100 · цель ${goal}]`;
  }

  if (step === 2) {
    return `Ок, идём дальше.\n\nЗадание: при основании a>1 неравенство log_a(f) ≥ 0 равносильно чему для f? Ответь одной строкой.\n\n[Текущий фокус: переход log ≥ 0] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 55/100]`;
  }

  return `ДЗ (бесплатный офлайн-трек):\n1) Выпиши ОДЗ для log_(x+2)(5-x)\n2) Реши log_2(x-1) ≥ 3\n3) Объясни, почему основание не может быть 1\n\nПришли ответы сюда — проверю по маркерам.\n\n[Текущий фокус: закрепление логов] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 60/100]\n\nℹ️ Сейчас офлайн-репетитор. Чтобы ИИ проверял свободнее и глубже бесплатно — добавь GEMINI_API_KEY (см. README).`;
}

function russianFlow(last: string, step: number, goal: string): string {
  if (step <= 1) {
    const ok =
      (/3|купл/.test(last) && /нн|причаст/.test(last)) ||
      (/нн/.test(last) && /купл/.test(last));
    if (ok) {
      return `Верно мыслишь про «купленный» — там НН.\n\nБаза: в полных причастиях с приставкой/зависимым словом обычно НН.\n\nСледующее: почему в «жареный картофель» одно Н? Ответь правилом.\n\n[Текущий фокус: Н/НН] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 50/100 · цель ${goal}]`;
    }
    return `Пока мимо.\n\nМикрошаг: выбери только слово с НН и назови часть речи (причастие/прилагательное).\nВарианты были: серебряный / жареный / купленный / нежданный.\n\n[Текущий фокус: Н/НН диагностика] | [Статус: 🟥 Пробел] | [Ментальный балл: 28/100]`;
  }

  if (step === 2) {
    return `Задание-микродиктант (ударения). Поставь ударение и пришли список:\n1) звонит\n2) торты\n3) средства\n4) баловать\n\n[Текущий фокус: орфоэпия] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 58/100]`;
  }

  return `ДЗ:\n1) 10 слов на ударения\n2) 5 пар паронимов (одеть/надеть и др.) — составь предложения\n3) Напиши проблему текста одним предложением (тренировка к №27)\n\n[Текущий фокус: русский ежедневный блок] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 62/100]\n\nℹ️ Для «умной» бесплатной проверки добавь GEMINI_API_KEY.`;
}

function infFlow(last: string, step: number, goal: string): string {
  if (step <= 1) {
    const ok = /3/.test(last) && (/1/.test(last) || /cab/.test(last));
    if (ok || /count\s*=\s*3|3\s+и\s+1|3\s*,\s*1/.test(last)) {
      return `По count('ABC') = 3 — верно.\n\nСледующий шаг: что вернёт find, если подстроки нет? И чем find отличается от index?\n\n[Текущий фокус: строки Python] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 52/100 · цель ${goal}]`;
    }
    return `Разберём код по частям.\n\nВопрос 1: сколько непересекающихся/подряд вхождений считает s.count('ABC') в 'ABCABCABC'? Ответь одним числом.\n\n[Текущий фокус: №24 строки] | [Статус: 🟥 Пробел] | [Ментальный балл: 30/100]`;
  }

  if (step === 2) {
    return `Задание: напиши псевдокод (5–8 строк) — найти длину самой длинной серии одинаковых символов в строке. Код Python пока не нужен.\n\n[Текущий фокус: №24 алгоритм] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 60/100]`;
  }

  return `ДЗ:\n1) Реализуй серию одинаковых символов на Python\n2) Оцени сложность\n3) Придумай тест из 3 строк\n\n[Текущий фокус: информатика 24] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 65/100]\n\nℹ️ Бесплатный «живой» ИИ: GEMINI_API_KEY или GROQ_API_KEY.`;
}

function essayFlow(last: string, step: number, goal: string): string {
  if (step <= 1) {
    const hasClaim = last.length > 25 && /(выбор|нельзя|можно|человек|жизнь)/.test(last);
    if (hasClaim) {
      return `Тезис принят как рабочий.\n\nПроверка К1: он отвечает на тему про выбор? Если да — ок.\n\nЗадание: назови одно литературное произведение и героя, которым докажешь тезис (пока без абзаца).\n\n[Текущий фокус: тезис → аргумент] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 48/100 · цель ${goal}]`;
    }
    return `Тезис слишком размытый или короткий.\n\nШаблон: «Я считаю, что …, потому что …».\nПерепиши тезис по теме выбора.\n\n[Текущий фокус: К1 тезис] | [Статус: 🟥 Пробел] | [Ментальный балл: 25/100]`;
  }

  if (step === 2) {
    return `Теперь напиши аргумент-абзац (120–180 слов):\nпример → пояснение связи с тезисом → микровывод.\n\n[Текущий фокус: К2 аргументация] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 58/100]`;
  }

  return `ДЗ: полное мини-сочинение 250–350 слов по новой теме:\n«Что важнее — мечта или ответственность?»\nСтруктура: тезис + 2 аргумента + вывод.\n\n[Текущий фокус: итоговое сочинение] | [Статус: 🟨 Нужна практика] | [Ментальный балл: 63/100]\n\nℹ️ Для глубокой проверки по критериям бесплатно подключи Gemini.`;
}

function reviewFlow(subject: SubjectKey, last: string, step: number): string {
  if (step <= 1 || last.length < 40) {
    return `Режим проверки. Пришли работу целиком:\n- математика: решение\n- русский/сочинение: текст\n- информатика: код или ответ\n\nПредмет сейчас: ${SUBJECTS[subject].title}.`;
  }

  return `Офлайн-проверка (кратко):\n1) Есть структура/ход мысли — ок, если текст не хаотичный.\n2) Найди сам 1 слабое место: где нет правила, ОДЗ, связи примера с тезисом или оценки сложности.\n3) Пришли исправленный фрагмент (не всё заново).\n\nДля разбора «как эксперт ФИПИ» бесплатно добавь GEMINI_API_KEY — тогда проверка станет намного глубже.`;
}

function blitzFlow(subject: SubjectKey, last: string, step: number): string {
  const tasks: Record<SubjectKey, string[]> = {
    MATH: [
      "Блиц-1: найди корень уравнения √(x-3)=x-5. Только ответ числом.",
      "Блиц-2: сколько целых решений у неравенства (x-1)(x-5)<0?",
      "Блиц-3: производная f(x)=x^3-3x в точке x=1 равна?",
    ],
    RUSSIAN: [
      "Блиц-1: ударение в слове «каталог» — какой слог?",
      "Блиц-2: одеть или надеть пальто? Одно слово.",
      "Блиц-3: нужно ли НН в слове «организованный» (причастие)? да/нет + почему.",
    ],
    INF: [
      "Блиц-1: сколько байт нужно, чтобы закодировать 50 символов алфавита мощности 8? (равномерный код)",
      "Блиц-2: чему равно 1101₂ в десятичной?",
      "Блиц-3: что вернёт len(set('abacaba'))?",
    ],
    ESSAY: [
      "Блиц-1: напиши тезис по теме «Дружба проходит проверку поступками».",
      "Блиц-2: одним предложением сформулируй связь аргумента с тезисом (любой пример).",
      "Блиц-3: напиши вывод из 2 предложений.",
    ],
  };

  const list = tasks[subject];
  const idx = Math.min(step, list.length) - 1;
  if (step === 0) return list[0];
  if (step >= list.length) {
    return `Блиц завершён. Краткий разбор: пришли свои ответы списком — отмечу что исправить.\nПоследний твой ввод учтён: «${last.slice(0, 80)}…»`;
  }
  return `Принято. Следующее без подсказки:\n\n${list[Math.max(idx, 0)]}`;
}
